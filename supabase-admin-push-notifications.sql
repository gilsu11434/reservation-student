-- 창의융합프로젝트실: 관리자 전용 아이폰 웹 푸시 구독 저장
-- Supabase SQL Editor에서 이 파일 전체를 한 번 실행하세요.

begin;

create table if not exists public.admin_push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint admin_push_endpoint_length_check
    check (char_length(endpoint) between 20 and 2048),
  constraint admin_push_p256dh_length_check
    check (char_length(p256dh) between 20 and 512),
  constraint admin_push_auth_length_check
    check (char_length(auth) between 8 and 512),
  constraint admin_push_user_agent_length_check
    check (user_agent is null or char_length(user_agent) <= 500)
);

create index if not exists admin_push_subscriptions_user_id_idx
on public.admin_push_subscriptions (user_id);

create table if not exists public.admin_push_delivery_log (
  id bigint generated by default as identity primary key,
  subscription_id uuid not null
    references public.admin_push_subscriptions(id) on delete cascade,
  event_key text not null,
  status text not null default 'claimed',
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  constraint admin_push_delivery_event_key_check
    check (char_length(event_key) between 1 and 250),
  constraint admin_push_delivery_status_check
    check (status in ('claimed', 'sent')),
  constraint admin_push_delivery_unique
    unique (subscription_id, event_key)
);

alter table public.admin_push_subscriptions enable row level security;
alter table public.admin_push_delivery_log enable row level security;

revoke all on table public.admin_push_subscriptions
from public, anon, authenticated;

revoke all on table public.admin_push_delivery_log
from public, anon, authenticated;

create or replace function public.admin_register_push_subscription(
  p_endpoint text,
  p_p256dh text,
  p_auth text,
  p_user_agent text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_subscription_id uuid;
begin
  if not exists (
    select 1
    from public.user_roles as user_role
    where user_role.user_id = auth.uid()
      and user_role.role::text = 'admin'
      and user_role.is_approved = true
  ) then
    raise exception '승인된 관리자만 휴대폰 알림을 등록할 수 있습니다.'
      using errcode = '42501';
  end if;

  if nullif(trim(coalesce(p_endpoint, '')), '') is null
    or nullif(trim(coalesce(p_p256dh, '')), '') is null
    or nullif(trim(coalesce(p_auth, '')), '') is null then
    raise exception '아이폰 알림 구독정보가 올바르지 않습니다.'
      using errcode = '22023';
  end if;

  insert into public.admin_push_subscriptions (
    user_id,
    endpoint,
    p256dh,
    auth,
    user_agent,
    enabled
  )
  values (
    auth.uid(),
    trim(p_endpoint),
    trim(p_p256dh),
    trim(p_auth),
    nullif(left(trim(coalesce(p_user_agent, '')), 500), ''),
    true
  )
  on conflict (endpoint) do update
  set
    user_id = excluded.user_id,
    p256dh = excluded.p256dh,
    auth = excluded.auth,
    user_agent = excluded.user_agent,
    enabled = true,
    updated_at = now()
  returning id into v_subscription_id;

  return v_subscription_id;
end;
$$;

create or replace function public.admin_unregister_push_subscription(
  p_endpoint text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1
    from public.user_roles as user_role
    where user_role.user_id = auth.uid()
      and user_role.role::text = 'admin'
      and user_role.is_approved = true
  ) then
    raise exception '승인된 관리자만 휴대폰 알림을 해제할 수 있습니다.'
      using errcode = '42501';
  end if;

  delete from public.admin_push_subscriptions
  where user_id = auth.uid()
    and endpoint = p_endpoint;
end;
$$;

create or replace function public.admin_push_subscription_enabled(
  p_endpoint text
)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select case
    when exists (
      select 1
      from public.user_roles as user_role
      where user_role.user_id = auth.uid()
        and user_role.role::text = 'admin'
        and user_role.is_approved = true
    ) then exists (
      select 1
      from public.admin_push_subscriptions as subscription
      where subscription.user_id = auth.uid()
        and subscription.endpoint = p_endpoint
        and subscription.enabled = true
    )
    else false
  end;
$$;

revoke all on function public.admin_register_push_subscription(
  text, text, text, text
) from public;
revoke all on function public.admin_unregister_push_subscription(text)
from public;
revoke all on function public.admin_push_subscription_enabled(text)
from public;

grant execute on function public.admin_register_push_subscription(
  text, text, text, text
) to authenticated;
grant execute on function public.admin_unregister_push_subscription(text)
to authenticated;
grant execute on function public.admin_push_subscription_enabled(text)
to authenticated;

commit;

select
  to_regclass('public.admin_push_subscriptions') is not null
    as subscriptions_ready,
  to_regclass('public.admin_push_delivery_log') is not null
    as delivery_log_ready;
